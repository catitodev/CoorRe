const MONTHS = {
  en: ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"],
  pt: ["JAN", "FEV", "MAR", "ABR", "MAI", "JUN", "JUL", "AGO", "SET", "OUT", "NOV", "DEZ"],
};

let current = "en";

export function language() {
  return current;
}

export function setLanguage(lang) {
  current = lang === "pt" ? "pt" : "en";
}

export function chooseLanguage({ query, stored }) {
  for (const candidate of [query, stored]) {
    if (candidate === "en" || candidate === "pt") return candidate;
  }
  return "en";
}

export function t(text, values = {}) {
  const template = current === "pt" ? PORTUGUESE[text] ?? text : text;
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in values ? String(values[key]) : match));
}

export function staticText(original) {
  if (current === "en") return original;
  const key = original.trim().replace(/\s+/g, " ");
  const translated = PORTUGUESE[key];
  return translated === undefined ? original : original.replace(original.trim(), translated);
}

export function decimal(text) {
  return current === "pt" ? text.replace(".", ",") : text;
}

export function grouped(n) {
  return n.toLocaleString(current === "pt" ? "pt-BR" : "en-US");
}

export function monthAbbreviation(index) {
  return MONTHS[current][index];
}

export function timeOfDay(date) {
  return date.toLocaleTimeString(current === "pt" ? "pt-BR" : "en-GB", { hour: "2-digit", minute: "2-digit" });
}
